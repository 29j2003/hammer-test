// fidelity_effects.h - "Game enhancements": the extra shaders of the mod's graphics add-on
// (mapbase-fidelity) on every material they are made for - liquid in bottles, sway in the wind,
// water with sun glint and foam - without deploy.bat. The rules and the material text are those
// of the add-on's deploy.ps1, so both write the same files (with its "generated" marker).
//
// Everything is on by default. The mod can switch an effect off completely or leave single
// models (or materials) out; the choices live in <mod>/cfg/mapsmith_enhancements.txt. Where
// deploy.bat would make a material that is switched off, a copy of the game's original with
// MAPSMITH_MARKER keeps it off (deploy.bat leaves such files alone, they count as the mod's own).
// Materials the mapper wrote by hand are never touched.

#pragma once

