// container_models.h - Liquid for containers on shared materials: own copies of their models
// (mapbase-fidelity's deploy.ps1, Get-ContainerModels / Remove-GeneratedModels, ported exactly).
//
// Some containers use a material they share with other things, or one whose name does not say
// "bottle" (Half-Life 2's garbage_glassbottle models are drawn from an atlas with cans and cartons).
// Changing that material would turn the cans into glass. Such a container (a model whose file
// name says bottle, jug, jar ...) gets its own copy of the .mdl in the mod: the material name in
// its texture table is changed in place - same length, the last four letters become "_flq" (or
// "_fq1".."_fq9" when that name is taken) - and points to a liquid material of its own (dark
// glass, kind Tinted). The .vvd, .vtx and .phy stay the game's: their checksum is in the .mdl
// header, which does not change. The copies are listed in <mod>/fidelity_models.txt with their
// SHA-256, in deploy.ps1's format, so deploy.bat and Mapsmith keep the same files: each removes
// only copies that are still unchanged and makes them again.

#pragma once

#include <cstddef>
#include <filesystem>
#include <map>
#include <optional>
#include <span>
#include <string>
#include <string_view>
#include <vector>

#include <sme/fidelity_effects.h>

namespace sme {

class GameFileSystem;

/// The last letters of an own material's name (the next free ones: "_fq1" .. "_fq9").
inline constexpr std::string_view OWN_MATERIAL_SUFFIX = "_flq";
/// The list of model copies in the mod folder ("path<TAB>SHA-256" lines).
inline constexpr std::string_view CONTAINER_MODELS_MANIFEST = "fidelity_models.txt";
/// Its first line, as deploy.ps1 writes it.
inline constexpr std::string_view CONTAINER_MODELS_HEADER =
	"// mapbase-fidelity: generated by deploy.ps1 (models) - copies of container models with their own liquid material: path, SHA-256";

/// One texture name in an .mdl's texture table and where its characters are in the file.
struct MdlTextureName {
	std::string name;          ///< As stored ("GlassJug01", may hold a sub folder)
	std::size_t offset = 0;    ///< Byte offset of the name in the .mdl
};
/// The material names of an .mdl (deploy.ps1's Read-MdlMaterials).
struct MdlMaterialTable {
	std::vector<MdlTextureName> textures;
	std::vector<std::string> folders;   ///< $cdmaterials, lower case with '/', ending in '/'
};
/// Reads the texture table and the $cdmaterials folders; nullopt for a damaged model (every
/// count and offset is checked against the file).
[[nodiscard]] std::optional<MdlMaterialTable> readMdlMaterialTable(std::span<const std::byte> mdl);

/// A container model that gets its own copy.
struct ContainerModel {
	std::string model;                ///< "models/props_junk/glassjug01.mdl"
	std::vector<std::byte> bytes;     ///< The copy: the game's .mdl with the own material names
	std::vector<std::string> own;     ///< Its own materials ("materials/models/props_junk/glassjug_flq.vmt")
};
/// The container models of the game (its own folders and archives, not the mod's) on materials
/// that are not named like a container, sorted by path. `ownSources`: own material -> the
/// game's material it copies (both "materials/....vmt").
struct ContainerModelScan {
	std::vector<ContainerModel> models;
	std::map<std::string, std::string> ownSources;
	std::vector<std::string> notes;   ///< "kept models/x.mdl (no free name for its own material)"
};
[[nodiscard]] ContainerModelScan findContainerModels(const GameFileSystem& fs, const std::filesystem::path& modDir);

/// Adds the container models to the plan of the Game enhancements, as deploy.ps1 does:
/// - every container model on another material gets its own liquid material (written like
///   deploy.ps1, kind Tinted) and its copy, while Liquid is on and the model is not left out;
/// - switched off or left out: the copy goes, and a copy of the original material (with
///   MAPSMITH_MARKER) at the own material's place keeps deploy.bat from making it again;
/// - without the mod's shader DLL nothing is made and the copies go (their materials go with
///   the other liquid ones);
/// - the mod's own models and materials are never touched; copies the mapper changed since stay.
/// `scan`: from findContainerModels (null: found now).
void planContainerModels(const GameFileSystem& fs, const std::filesystem::path& modDir, const EnhancementSettings& settings, bool shaderDll,
                         EnhancementPlan& plan, const ContainerModelScan* scan = nullptr);

} // namespace sme
