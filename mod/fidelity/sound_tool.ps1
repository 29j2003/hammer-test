<#
.SYNOPSIS
    mapbase-fidelity sound tool: makes the game's sounds fuller ("beefier"),
    as copies in the mod - the originals stay as they are.

.DESCRIPTION
    Reads the sounds of one or more folders (default: weapons) from the
    game's .vpk archives, gives them more bass, a little more bite and some
    soft saturation (sound_beef.cs), and writes them into the mod's sound
    folder, where the game takes them instead of its own. The loudest point
    stays as loud as before, so the game's mix stays right.

    Only plain .wav files (PCM, 8/16 bit) are changed; compressed ones (MP3,
    ADPCM) are left out and counted. A list of the copies (fidelity_sounds.txt)
    lets a second run with the same settings skip them, and -Remove take them
    away again. Sounds the mod has itself are never overwritten; a copy
    changed by hand is never removed.

.PARAMETER GamePath
    The mod folder (with gameinfo.txt). Optional: found in Steam like deploy.bat.

.PARAMETER Folder
    Sound folders below sound/, e.g. weapons, physics, ambient. Default: weapons.

.PARAMETER Preset
    subtle, beefy (default) or heavy.

.PARAMETER Bass
    Low shelf at 120 Hz in dB (replaces the preset's).

.PARAMETER Bite
    High shelf at 3.5 kHz in dB (replaces the preset's).

.PARAMETER Drive
    Soft saturation 0..1 (replaces the preset's).

.PARAMETER Pitch
    Semitones, negative = deeper (replaces the preset's). Not for sounds with loops.

.PARAMETER Remove
    Remove all copies this tool made.

.EXAMPLE
    sound_tool.bat
    sound_tool.bat -Preset heavy
    sound_tool.bat -Folder weapons,physics -Bass 6
    sound_tool.bat -Remove
#>
param(
    [string]$GamePath = '',
    [string[]]$Folder = @('weapons'),
    [ValidateSet('subtle', 'beefy', 'heavy')][string]$Preset = 'beefy',
    [string]$Bass = '',
    [string]$Bite = '',
    [string]$Drive = '',
    [string]$Pitch = '',
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
. (Join-Path $Root 'fidelity_common.ps1')
$SoundsManifest = 'fidelity_sounds.txt'
$SoundsHeader = '// mapbase-fidelity: generated by sound_tool.ps1 - fuller copies of the game''s sounds: path, SHA-256, settings'

# bass dB, bite dB, drive, pitch semitones
$Presets = @{
    subtle = @(3.0, 1.0, 0.15, 0.0)
    beefy = @(5.0, 2.0, 0.3, -0.5)
    heavy = @(7.0, 3.0, 0.5, -1.0)
}

# ---------------------------------------------------------------- locate ---
# (a path ending in \" arrives with the quote: "D:\...\mymod\" in a .bat)
if ($GamePath) { $GamePath = $GamePath.Trim().Trim('"').TrimEnd('\', '/') }
if (-not $GamePath) { $GamePath = Find-ModFolder }
if (-not $GamePath) { $GamePath = ([string](Read-Host "Mod folder (steamapps\sourcemods\<mod>, the one with gameinfo.txt)")).Trim().Trim('"') }
if (-not $GamePath -or -not (Test-Path -LiteralPath (Join-Path $GamePath 'gameinfo.txt'))) {
    throw "'$GamePath' has no gameinfo.txt. Pass the mod folder as -GamePath."
}
$Game = (Resolve-Path -LiteralPath $GamePath).Path

# The copies listed so far: @{ path = @{ Hash; Settings } }
function Read-SoundsManifest {
    $list = @{}
    $manifest = Join-Path $Game $SoundsManifest
    if (-not (Test-Path -LiteralPath $manifest)) { return $list }
    foreach ($line in (Read-Text $manifest) -split "`r?`n") {
        if (-not $line -or $line.StartsWith('//')) { continue }
        $parts = $line -split "`t"
        if ($parts.Count -ge 3) { $list[$parts[0]] = @{ Hash = $parts[1]; Settings = $parts[2] } }
    }
    return $list
}

# Removes the listed copies not in $Keep (unchanged ones only); writes the list of $Keep
function Update-Sounds([hashtable]$Keep) {
    $old = Read-SoundsManifest
    foreach ($key in $old.Keys) {
        if ($Keep.ContainsKey($key)) { continue }
        $file = Get-SafeTarget $Game $key
        if (-not $file -or -not (Test-Path -LiteralPath $file -PathType Leaf)) { continue }
        if ((Get-BytesHash ([System.IO.File]::ReadAllBytes($file))) -eq $old[$key].Hash) { Remove-Item -LiteralPath $file -Force }
        else { Write-Host "  kept     $key (changed since the sound tool made it)" }
    }
    $manifest = Join-Path $Game $SoundsManifest
    if ($Keep.Count -eq 0) {
        if (Test-Path -LiteralPath $manifest) { Remove-Item -LiteralPath $manifest -Force }
        return
    }
    $lines = @($SoundsHeader)
    foreach ($key in ($Keep.Keys | Sort-Object)) { $lines += "$key`t$($Keep[$key].Hash)`t$($Keep[$key].Settings)" }
    Write-Text $manifest (($lines -join "`r`n") + "`r`n")
}

if ($Remove) {
    Update-Sounds @{}
    Write-Host "Done. The sounds of the sound tool are gone."
    exit 0
}

# ------------------------------------------------------------- settings ---
# ("-Bass 4,5" as well as "4.5": powershell -File read "0,5" as 5)
$values = @($Presets[$Preset])
if ($Bass) { $values[0] = ConvertTo-Number $Bass 'Bass' -24 24 }
if ($Bite) { $values[1] = ConvertTo-Number $Bite 'Bite' -24 24 }
if ($Drive) { $values[2] = ConvertTo-Number $Drive 'Drive' 0 1 }
if ($Pitch) { $values[3] = ConvertTo-Number $Pitch 'Pitch' -12 12 }
$culture = [System.Globalization.CultureInfo]::InvariantCulture
$settings = 'bass {0} bite {1} drive {2} pitch {3}' -f @($values | ForEach-Object { $_.ToString('0.##', $culture) })
# ("-Folder weapons,physics" arrives from sound_tool.bat as one text)
$prefixes = @(Split-List $Folder | ForEach-Object { 'sound/' + $_.Trim().Trim('/', '\').Replace('\', '/').ToLowerInvariant() } | Where-Object { $_ -ne 'sound/' -and $_ -notmatch '\.\.' })
if ($prefixes.Count -eq 0) { throw "No sound folder given (-Folder weapons)." }
Write-Host "mapbase-fidelity sound tool -> $Game"
Write-Host "  folders  $($prefixes -join ', ')   settings  $settings"

if (-not ('FidelitySoundBeef' -as [type])) { Add-Type -Path (Join-Path $Root 'sound_beef.cs') }

# ------------------------------------------------------------- sounds ---
$old = Read-SoundsManifest
$made = @{}
$script:New = 0
$script:Skipped = 0
$script:Bytes = [int64]0
$want = {
    param($ext, $dir, $name)
    if ($ext -ne 'wav') { return $false }
    $d = $dir.ToLowerInvariant()
    foreach ($p in $prefixes) { if ($d -eq $p -or $d.StartsWith($p + '/')) { return -not $made.ContainsKey("$d/$($name.ToLowerInvariant()).wav") } }
    return $false
}
$process = {
    param($key, $bytes)
    $key = $key.ToLowerInvariant()
    if ($made.ContainsKey($key)) { return }
    $target = Get-SafeTarget $Game $key
    if (-not $target) { return }
    if (Test-Path -LiteralPath $target -PathType Leaf) {
        $hash = Get-BytesHash ([System.IO.File]::ReadAllBytes($target))
        if (-not $old.ContainsKey($key) -or $old[$key].Hash -ne $hash) { return }	# the mod's own, or changed by hand
        if ($old[$key].Settings -eq $settings) { $made[$key] = $old[$key]; return }
    }
    $reason = $null
    $out = [FidelitySoundBeef]::Process($bytes, $values[0], $values[1], $values[2], $values[3], [ref]$reason)
    if (-not $out) { $script:Skipped++; return }
    New-Item -ItemType Directory -Force -Path (Split-Path $target -Parent) | Out-Null
    [System.IO.File]::WriteAllBytes($target, $out)
    $script:New++
    $script:Bytes += $out.Length
    $made[$key] = @{ Hash = (Get-BytesHash $out); Settings = $settings }
    Add-ManifestLine $Game $SoundsManifest $SoundsHeader $key $made[$key].Hash $settings
}
foreach ($vpkFolder in Get-VpkFolders $Game) {
    foreach ($vpk in Get-SoundVpks $vpkFolder) {
        Write-Host "  reading  $($vpk.Name)"
        Read-VpkFiles $vpk.FullName $want -Each $process -Ext 'wav' | Out-Null
    }
}
# Copies of folders no longer asked for stay (another run may have made them):
# only the ones of these folders that are gone from the game are removed
foreach ($key in $old.Keys) {
    $inFolders = $false
    foreach ($p in $prefixes) { if ($key.StartsWith($p + '/')) { $inFolders = $true } }
    if (-not $inFolders -and -not $made.ContainsKey($key)) { $made[$key] = $old[$key] }
}
Update-Sounds $made

Write-Host ("  sounds   {0} fuller ({1} new, {2:N1} MB), {3} left as they are (compressed or unusual format)" -f
    $made.Count, $script:New, ($script:Bytes / 1MB), $script:Skipped)
Write-Host "Done. Start the mod (restart it if it was running). To undo: sound_tool.bat -Remove"
